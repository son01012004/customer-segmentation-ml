def run_visualization_pipeline(
    *,
    segmentation_id: str | None = None,
    segmentation_manifest_path: Path | str | None = None,
    evaluation_manifest_paths: list[Path | str] | None = None,
    marketing_manifest_path: Path | str | None = None,
    output_dir: Path | str | None = None,
    config_path: Path | str | None = None,
    dev02_config_path: Path | str | None = None,
    output_format: str | None = None,
    force_rerun: bool = False,
    log_dir: Path | str | None = None,
) -> VisualizationPipelineResult:
    """Run the DEV-08 visualization pipeline.

    Parameters
    ----------
    segmentation_id : str or None
        DEV-06 ``segmentation_id`` (``^seg_[0-9a-f]{24}$``). Mutually
        exclusive with ``segmentation_manifest_path``.
    segmentation_manifest_path : pathlib.Path or str or None
        Explicit path to a DEV-06 ``segmentation_manifest.json``.
    evaluation_manifest_paths : list[Path | str] or None
        List of paths to DEV-05 ``evaluation_manifest.json`` files
        (may be empty for segmentation-only dashboards).
    marketing_manifest_path : pathlib.Path or str or None
        Optional path to a DEV-07 ``marketing_manifest.json``. When
        ``None``, the marketing section renders REVIEW_REQUIRED.
    output_dir : pathlib.Path or str or None
        Directory to write the dashboard into. When None, the
        canonical per-segmentation directory under the storage root
        is used (one subdirectory per ``dashboard_id``).
    config_path : pathlib.Path or str or None
        Path to the DEV-08 config YAML (default:
        ``configs/dev08_visualization.yaml``).
    dev02_config_path : pathlib.Path or str or None
        Forwarded to the visualization storage root resolution so
        DEV-08 reads the same storage root that DEV-02/03/04 used.
        ``None`` uses the canonical default.
    output_format : str or None
        Override the chart output format (``png`` or ``svg``).
    force_rerun : bool
        If True, ignore the idempotency cache and write a fresh
        dashboard.
    log_dir : pathlib.Path or str or None
        Directory for the per-stage log file. If None, no file log
        is emitted (console only).

    Returns
    -------
    VisualizationPipelineResult

    Raises
    ------
    VisualizationInputError
        On CLI arg / path errors.
    VisualizationError
        On storage path resolution failure.
    """
    # ---- Stage A: preflight --------------------------------------------------
    if segmentation_id is None and segmentation_manifest_path is None:
        raise VisualizationInputError(
            "Either --segmentation-id or --segmentation-manifest-path must be provided."
        )
    if segmentation_id is not None and segmentation_manifest_path is not None:
        raise VisualizationInputError(
            "--segmentation-id and --segmentation-manifest-path are mutually exclusive."
        )
    if evaluation_manifest_paths is None:
        evaluation_manifest_paths = []
    if not isinstance(evaluation_manifest_paths, list):
        raise VisualizationInputError(
            "evaluation_manifest_paths must be a list; got "
            f"{type(evaluation_manifest_paths).__name__}."
        )

    config: Dev08Config = load_dev08_config(config_path)
    storage_root = resolve_storage_root(dev02_config_path)
    log_file = None
    if log_dir is not None:
        log_dir_p = Path(log_dir)
        log_dir_p.mkdir(parents=True, exist_ok=True)
        log_file = log_dir_p / "dev08_visualization.log"

    logger = configure_logging(
        level=config.logging.level,
        fmt=config.logging.format,
        log_file=log_file,
        emit_to_console=config.logging.emit_to_console,
    )
    per_stage = PerStageLogger(logger, stage="A")

    # ---- Stage B: load manifests --------------------------------------------
    per_stage.stage_start("B")
    try:
        if segmentation_manifest_path is not None:
            seg_path = Path(segmentation_manifest_path)
            seg_manifest: SegmentationManifest = load_segmentation_manifest(seg_path)
        else:
            seg_manifest, seg_path = _resolve_segmentation_manifest(
                segmentation_id=str(segmentation_id),
                storage_root=storage_root,
            )
        eval_manifests: list[EvaluationManifest] = []
        eval_paths: list[Path] = []
        for p in evaluation_manifest_paths:
            pp = Path(p)
            eval_manifests.append(load_evaluation_manifest(pp))
            eval_paths.append(pp)
        mkt_manifest: MarketingRecommendationManifest | None = None
        mkt_path: Path | None = None
        if marketing_manifest_path is not None:
            mkt_path = Path(marketing_manifest_path)
            mkt_manifest = load_marketing_manifest(mkt_path)
        per_stage.stage_end("PASS")
    except VisualizationError:
        per_stage.stage_end("FAIL")
        finalize_logging(logger)
        raise

    # ---- Stage C: validate cross-manifest invariants -------------------------
    per_stage.stage_start("C")
    try:
        cross_notes: list[str] = []
        validation_passed = True
        # Cross-check: segmentation_id matches evaluation's
        # segmentation_id pointer (DEV-05's segmentation_id field).
        # Note: EvaluationManifest has segmentation_id; we accept
        # either by checking both segmentation_id and clustering_id
        # fields. If the field is missing we skip the cross-check
        # (older manifests).
        for i, ev in enumerate(eval_manifests):
            try:
                ev_seg_id = str(ev.segmentation_id) if hasattr(ev, "segmentation_id") else None
            except Exception:
                ev_seg_id = None
            if ev_seg_id and ev_seg_id != seg_manifest.segmentation_id:
                cross_notes.append(
                    f"evaluation[{i}] segmentation_id={ev_seg_id!r} does not match "
                    f"input segmentation_id={seg_manifest.segmentation_id!r}; skipped"
                )
                validation_passed = False
        # Cross-check: marketing manifest segmentation_id matches.
        if (
            mkt_manifest is not None
            and hasattr(mkt_manifest, "segmentation_id")
            and mkt_manifest.segmentation_id != seg_manifest.segmentation_id
        ):
            cross_notes.append(
                f"marketing segmentation_id={mkt_manifest.segmentation_id!r} "
                f"does not match input segmentation_id="
                f"{seg_manifest.segmentation_id!r}"
            )
            validation_passed = False
        per_stage.stage_end("PASS" if validation_passed else "WARN")
    except VisualizationError:
        per_stage.stage_end("FAIL")
        finalize_logging(logger)
        raise

    # ---- Stage D: resolve output dir ----------------------------------------
    per_stage.stage_start("D")
    try:
        # Build config_sha256 from the canonical config text on disk
        # (so a config edit invalidates the dashboard_id).
        from customer_segmentation.prototype.visualization.config_loader import (
            DEFAULT_DEV08_CONFIG_PATH,
        )

        config_path = Path(config_path) if config_path is not None else DEFAULT_DEV08_CONFIG_PATH
        config_text = config_path.read_text(encoding="utf-8")
        config_sha256 = compute_config_sha256(config_text)

        dataset_id = str(seg_manifest.dataset_id)
        preprocessed_id = str(seg_manifest.preprocessed_id)
        clustering_id = str(seg_manifest.clustering_id)
        dashboard_id = derive_dashboard_id(
            segmentation_id=str(seg_manifest.segmentation_id),
            clustering_id=clustering_id,
            preprocessed_id=preprocessed_id,
            dataset_id=dataset_id,
            config_sha256=config_sha256,
        )

        if output_dir is not None:
            run_dir = Path(output_dir).resolve()
            run_dir.mkdir(parents=True, exist_ok=True)
        else:
            base = prototype_visualization_base_dir(
                storage_root,
                dataset_id=dataset_id,
                preprocessed_id=preprocessed_id,
                clustering_id=clustering_id,
                segmentation_id=str(seg_manifest.segmentation_id),
            )
            run_dir = prototype_visualization_run_dir(
                storage_root,
                dataset_id=dataset_id,
                preprocessed_id=preprocessed_id,
                clustering_id=clustering_id,
                segmentation_id=str(seg_manifest.segmentation_id),
                dashboard_id=dashboard_id,
            )
            run_dir.mkdir(parents=True, exist_ok=True)
        per_stage.stage_end("PASS")
    except (VisualizationError, OSError) as exc:
        per_stage.stage_end("FAIL")
        finalize_logging(logger)
        if isinstance(exc, VisualizationError):
            raise
        raise VisualizationError(f"Failed to resolve run_dir: {exc}") from exc

    # ---- Stage E: generate ---------------------------------------------------
    per_stage.stage_start("E")
    try:
        generator = DashboardGenerator(
            config=config,
            segmentation_manifest=seg_manifest,
            evaluation_manifests=eval_manifests,
            marketing_manifest=mkt_manifest,
            run_dir=run_dir,
            output_format=output_format,
        )
        records = generator.generate()
        # Build the DashboardResult.
        result = build_dashboard_result(
            dashboard_id=dashboard_id,
            segmentation_manifest=seg_manifest,
            clustering_id=clustering_id,
            preprocessed_id=preprocessed_id,
            dataset_id=dataset_id,
            run_dir=run_dir,
            lifecycle=LIFECYCLE_SUCCESS,
            validation_passed=validation_passed,
            charts=records,
            input_segmentation_manifest_path=seg_path,
            input_evaluation_manifest_paths=eval_paths,
            input_marketing_manifest_path=mkt_path,
            notes=cross_notes,
        )

        # Write summary text + JSON sidecar.
        summary_text = format_dashboard_summary(result)
        summary_text_path = run_dir / "dashboard_summary.txt"
        summary_text_path.write_text(summary_text, encoding="utf-8")
        summary_json_path = run_dir / "dashboard_summary.json"
        summary_json_path.write_text(dashboard_result_to_json(result), encoding="utf-8")
        per_stage.stage_end("PASS")
    except VisualizationError:
        per_stage.stage_end("FAIL")
        finalize_logging(logger)
        raise

    # ---- Stage F: finalize ---------------------------------------------------
    per_stage.stage_start("F")
    try:
        pipe_result = VisualizationPipelineResult(
            lifecycle=LIFECYCLE_SUCCESS,
            result=result,
            run_dir=run_dir,
            summary_text_path=summary_text_path,
            summary_json_path=summary_json_path,
            cached=False,
            validation_passed=validation_passed,
            notes=cross_notes,
        )
        per_stage.stage_end("PASS")
    finally:
        finalize_logging(logger)

    return pipe_result


