"""Visualization pipeline for DEV-08 Prototype Visualization Dashboard.

The :class:`VisualizationPipeline` is the orchestrator. It composes
the existing manifest loaders, the storage helpers, and the
:class:`DashboardGenerator` into one Stage A → F pipeline.

Stages
------
- **A (preflight)** — load DEV-08 config; resolve storage root.
- **B (load)** — read segmentation / evaluation / marketing manifests
  via :mod:`customer_segmentation.prototype.visualization.loaders`.
- **C (validate)** — input contract checks (manifest schemas are
  validated by the readers; this stage verifies the cross-manifest
  invariants: segmentation_id matches across manifests, etc.).
- **D (resolve output)** — compute ``dashboard_id`` and run_dir via
  :mod:`customer_segmentation.prototype.visualization.storage`.
- **E (generate)** — call :class:`DashboardGenerator.generate`;
  write chart files + text artefacts + summary + JSON sidecar.
- **F (finalize)** — return the :class:`DashboardResult`.

Hard rules
----------
- The pipeline never modifies input manifests.
- The pipeline never writes outside the resolved run_dir.
- The pipeline never promotes prototype artefacts to research
  evidence.
- Cluster Visualization 2D remains BLOCKED — the pipeline does NOT
  fabricate a chart for it.
- Marketing content is never generated by the pipeline.
- All text outputs are scanned for banned substrings (the
  ``format_dashboard_*`` helpers do this internally).
"""

