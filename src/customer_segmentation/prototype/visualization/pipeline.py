def _resolve_segmentation_manifest(
    *,
    segmentation_id: str,
    storage_root: Path,
) -> tuple[SegmentationManifest, Path]:
    """Locate the DEV-06 segmentation manifest for ``segmentation_id``.

    Scans the canonical ``<storage_root>/datasets/.../segmentation/<seg_id>/``
    tree for a ``segmentation_manifest.json`` whose
    ``segmentation_id`` matches the requested id.

    Raises
    ------
    VisualizationError
        If the id is missing, the file is not found, or the file's
        ``segmentation_id`` does not match.
    """
    import re

    if not isinstance(segmentation_id, str) or not segmentation_id:
        raise VisualizationInputError(
            f"segmentation_id must be a non-empty str; got {segmentation_id!r}."
        )
    if not re.match(r"^seg_[0-9a-f]{24}$", segmentation_id):
        raise VisualizationInputError(
            f"segmentation_id {segmentation_id!r} does not match required format "
            f"^seg_[0-9a-f]{{24}}$."
        )
    storage_root = Path(storage_root).resolve()
    # ``storage_root`` already points at ``<repo>/data/prototype/datasets``
    # (per ``configs/dev02_dataset_management.yaml``); the canonical
    # on-disk layout starts directly under it (no extra ``"datasets"``
    # literal). Mirrors the canonical layout produced by DEV-02..08 — see
    # the regression test in
    # ``tests/test_dev04_storage.py::TestPathDoublingRegressionA1``.
    candidate_dir = storage_root
    matches: list[Path] = []
    if candidate_dir.exists():
        # The canonical layout has nested directories:
        # <storage_root>/<dataset_id>/preprocessed/<pp_id>/clustering/<cl_id>/segmentation/<seg_id>/segmentation_manifest.json
        # Use ** to traverse all levels.
        for mf in sorted(
            candidate_dir.glob(f"**/segmentation/{segmentation_id}/segmentation_manifest.json")
        ):
            matches.append(mf)
    if not matches:
        raise VisualizationError(
            f"Could not find segmentation_manifest.json for segmentation_id "
            f"{segmentation_id!r} under {candidate_dir!s}."
        )
    # If multiple matches exist, pick the first by sorted order for determinism.
    path = matches[0]
    manifest = load_segmentation_manifest(path)
    if manifest.segmentation_id != segmentation_id:
        raise VisualizationError(
            f"Found manifest at {path} but its segmentation_id is "
            f"{manifest.segmentation_id!r} (expected {segmentation_id!r})."
        )
    return manifest, path
